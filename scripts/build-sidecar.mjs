#!/usr/bin/env node
/**
 * NOVA — desktop sidecar builder
 * ==============================
 * Produces ONE self-contained executable that serves the API *and* the built
 * web UI from memory. The Tauri shell ships it as a resource and spawns it.
 *
 *   node scripts/build-sidecar.mjs [--target node20-win-x64|node20-linux-x64] [--skip-pkg]
 *
 * Steps:
 *   1. embed apps/web/dist into apps/worker/src/web-assets.generated.ts
 *   2. bundle apps/worker/src/standalone.ts with esbuild (CJS, node)
 *   3. package with @yao-pkg/pkg into a single executable
 *
 * AI models are never embedded — the binary only contains our code + the UI.
 */
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const targetIdx = args.indexOf('--target');
const TARGET = targetIdx === -1 ? 'node20-linux-x64' : args[targetIdx + 1];
const SKIP_PKG = args.includes('--skip-pkg');

const DIST = path.join(root, 'apps/web/dist');
const OUT_DIR = path.join(root, 'build/sidecar');
const isWin = TARGET.includes('win');
const EXE_NAME = isWin ? 'nova-server.exe' : 'nova-server';

// ------------------------------------------------------------ 1. embed assets
function walk(dir, base = '') {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = `${base}/${name}`;
    if (statSync(full).isDirectory()) out.push(...walk(full, rel));
    else out.push([rel, full]);
  }
  return out;
}

if (!existsSync(path.join(DIST, 'index.html'))) {
  console.error('❌ apps/web/dist is missing or empty. Run `npm run build` first.');
  process.exit(1);
}

const files = walk(DIST);
const entries = files.map(([rel, full]) => {
  const b64 = readFileSync(full).toString('base64');
  return `  ${JSON.stringify(rel)}: { m: ${JSON.stringify(mimeFor(rel))}, d: ${JSON.stringify(b64)} },`;
});
function mimeFor(rel) {
  const e = path.extname(rel);
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json; charset=utf-8',
      '.svg': 'image/svg+xml',
      '.png': 'image/png',
      '.ico': 'image/x-icon',
      '.woff2': 'font/woff2',
      '.map': 'application/json',
    }[e] ?? 'application/octet-stream'
  );
}

const generated = `/**
 * GENERATED — do not edit by hand.
 * Embedded web UI for the standalone desktop server (${files.length} files from apps/web/dist).
 * Regenerated by scripts/build-sidecar.mjs.
 */
export interface EmbeddedAsset { m: string; d: string }

export const WEB_ASSETS: Record<string, EmbeddedAsset> = {
${entries.join('\n')}
};
`;
writeFileSync(path.join(root, 'apps/worker/src/web-assets.generated.ts'), generated);
console.log(`✅ embedded ${files.length} web assets (${(generated.length / 1024 / 1024).toFixed(2)} MB of source)`);

// ------------------------------------------------------------------ 2. bundle
mkdirSync(OUT_DIR, { recursive: true });
const BUNDLE = path.join(OUT_DIR, 'nova-server.cjs');

/**
 * pkg cannot execute dynamic `import()` inside its snapshot
 * (ERR_VM_DYNAMIC_IMPORT_CALLBACK_MISSING). The app source lazily imports
 * node:fs / node:path so the SAME files stay importable from Cloudflare
 * Workers. For the sidecar bundle only, rewrite those lazy imports to
 * `require(...)`, which pkg handles natively. The Workers build is untouched.
 */
const pkgDynamicImportFix = {
  name: 'pkg-dynamic-import-fix',
  setup(b) {
    b.onLoad({ filter: /\.ts$/ }, async (a) => {
      const src = readFileSync(a.path, 'utf8');
      const out = src.replace(
        /await\s+import\(\s*(['"])node:(fs|path|fs\/promises|os|child_process)\1\s*\)/g,
        (_m, q, mod) => `require(${q}node:${mod}${q})`,
      );
      return out === src ? null : { contents: out, loader: 'ts' };
    });
  },
};

await build({
  entryPoints: [path.join(root, 'apps/worker/src/standalone.ts')],
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'cjs',
  outfile: BUNDLE,
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [pkgDynamicImportFix],
  // node builtins stay external; everything else is inlined
});
console.log(`✅ bundled → ${path.relative(root, BUNDLE)}`);

// ------------------------------------------------------------------- 3. package
if (SKIP_PKG) {
  console.log('⏭  --skip-pkg: left the CJS bundle un-packaged');
} else {
  const out = path.join(OUT_DIR, EXE_NAME);
   execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['--yes', '@yao-pkg/pkg', BUNDLE, '--targets', TARGET, '--output', out], {
    stdio: 'inherit',
    cwd: root, shell: true,
  });
  const size = statSync(out).size;
  console.log(`✅ packaged → ${path.relative(root, out)} (${(size / 1024 / 1024).toFixed(1)} MB)`);

  // drop a copy where the Tauri build expects its resource
  const sidecarDir = path.join(root, 'apps/desktop/src-tauri/sidecar');
  mkdirSync(sidecarDir, { recursive: true });
  copyFileSync(out, path.join(sidecarDir, EXE_NAME));
  console.log(`✅ copied into apps/desktop/src-tauri/sidecar/${EXE_NAME}`);
}
